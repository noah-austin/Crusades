"""Generate narration audio from script.json with the Kokoro voice model.

Usage: python voice.py <script.json> <model.onnx> <voices.bin> <out_dir> [segment ids...]

Writes <out_dir>/audio/<id>.mp3 for each segment and <out_dir>/narration.js with
timings (cues) so the page can show subtitles in sync and pace scenes to the voice.
Segments whose mp3 already exists are skipped, so the run can be resumed.
"""
import json, os, subprocess, sys, tempfile
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

script_path, model, voices, out = sys.argv[1:5]
only = set(sys.argv[5:])
VOICES = {"n": ("bm_george", 0.94), "q": ("bm_fable", 0.9)}
PAUSE = {"title": 0.9, "line": 0.42, "quote": 0.75, "phase": 0.7}
SR = 24000

k = Kokoro(model, voices)
segments = json.load(open(script_path))
os.makedirs(os.path.join(out, "audio"), exist_ok=True)
timing_path = os.path.join(out, "timings.json")
timings = json.load(open(timing_path)) if os.path.exists(timing_path) else {}


def fname(seg_id):
    return seg_id.replace(":", "-") + ".mp3"


for seg in segments:
    sid = seg["id"]
    if only and sid not in only:
        continue
    mp3 = os.path.join(out, "audio", fname(sid))
    if os.path.exists(mp3) and sid in timings:
        continue
    pieces, cues, t = [], [], 0.35
    pieces.append(np.zeros(int(SR * 0.35), dtype=np.float32))
    for it in seg["items"]:
        if it["kind"] == "quote":
            pieces.append(np.zeros(int(SR * 0.35), dtype=np.float32)); t += 0.35
        voice, speed = VOICES[it["voice"]]
        audio, sr = k.create(it["say"], voice=voice, speed=speed, lang="en-gb")
        assert sr == SR
        audio = audio.astype(np.float32)
        d = len(audio) / SR
        cue = {"t": round(t, 3), "d": round(d, 3), "kind": it["kind"], "sub": it["sub"]}
        for key in ("source", "phase"):
            if key in it:
                cue[key] = it[key]
        cues.append(cue)
        pieces.append(audio)
        gap = PAUSE[it["kind"]]
        pieces.append(np.zeros(int(SR * gap), dtype=np.float32))
        t += d + gap
    wav = np.concatenate(pieces)
    peak = float(np.max(np.abs(wav))) or 1.0
    wav = wav * (0.89 / peak)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        sf.write(tmp.name, wav, SR)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", tmp.name, "-ac", "1", "-ar", "24000",
                        "-codec:a", "libmp3lame", "-b:a", "48k", mp3], check=True)
        os.unlink(tmp.name)
    timings[sid] = {"src": "audio/" + fname(sid), "dur": round(len(wav) / SR, 3), "cues": cues}
    json.dump(timings, open(timing_path, "w"))
    print(sid, round(len(wav) / SR, 1), "s", flush=True)

with open(os.path.join(out, "narration.js"), "w") as f:
    f.write("// Generated by tools/voice.py from tools/build-script.js. Do not edit by hand.\n")
    f.write("window.NARRATION = " + json.dumps(timings, ensure_ascii=False) + ";\n")
print("done", len(timings))
